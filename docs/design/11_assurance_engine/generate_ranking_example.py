"""Hand-worked example of Algorithm 5 (hybrid ranking) with the weights of config 1.4.0 (DA-22, Student 1 for Student 2).

    python generate_ranking_example.py   ->  ranking_example_results.md

Five SYNTHETIC items for the query "drill" by a borrower whose home community is A. The input values are chosen by
hand to show each rule of the formula, not measured. The script is the oracle for the HybridRanker unit test (suite 29),
as generate_khop_example.py was for k-hop in iteration 1.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(HERE, "Assurance_Engine_Config_v1.4.0.json"), encoding="utf-8"))
R = CFG["ranking_alg5"]
W = R["weights"]
MIX = R["retrieval"]["relevance_mix"]
MIN_REL = R["retrieval"]["min_relevance"]
N_MIN = CFG["decision_policy_alg4"]["thresholds"]["n_min_effective_observations"]
HALF_LIFE = R["freshness"]["half_life_days"]
POP_BASELINE = 0.78          # assumed population baseline for LENDER / CONDITION_AGREED in this example

# id, title, semantic cosine, normalised keyword score, lender (mean, n_eff), availability, same community, age in days
ITEMS = [
    ("I1", "Cordless drill", 0.82, 1.00, (0.91, 6.2), 1.0, 1, 10),
    ("I2", "Drill machine (new lender)", 0.78, 0.80, (0.50, 0.0), 1.0, 1, 3),
    ("I3", "Hammer drill (dates taken)", 0.74, 0.90, (0.62, 4.0), 0.0, 1, 40),
    ("I4", "Screwdriver set", 0.55, 0.00, (0.88, 5.1), 1.0, 1, 5),
    ("I5", "Drill (second community)", 0.80, 1.00, (0.85, 3.4), 1.0, 0, 20),
    ("I6", "Garden hose", 0.18, 0.00, (0.95, 9.0), 1.0, 1, 2),
]


def lender_value(mean, n_eff):
    """Posterior mean when there is enough evidence, otherwise the population baseline: never a penalty (claim C5)."""
    return mean if n_eff >= N_MIN else POP_BASELINE


def score(item):
    _, _, sem, kw, (mean, n_eff), avail, same, age = item
    rel = MIX["semantic"] * sem + MIX["keyword"] * kw
    parts = {"relevance": rel, "lender_evidence": lender_value(mean, n_eff), "availability": avail,
             "same_community": float(same), "freshness": 2 ** (-age / HALF_LIFE)}
    total = sum(W[k] * v for k, v in parts.items())
    return rel, parts, total


def main():
    rows = []
    for it in ITEMS:
        rel, parts, total = score(it)
        rows.append((it, rel, parts, total))
    kept = [r for r in rows if r[1] >= MIN_REL]
    kept.sort(key=lambda r: -r[3])
    L = ["# Algorithm 5 worked example: hybrid ranking (generated)", "",
         "| Field | Value |", "|---|---|",
         f"| Config | {CFG['config_metadata']['config_version']}, section `ranking_alg5` |",
         "| Generated by | `generate_ranking_example.py` (do not edit by hand) |",
         "| Data | SYNTHETIC values chosen by hand to exercise each rule; not measurements |", "",
         f"Query \"drill\", borrower's home community A, dates given. Weights: relevance {W['relevance']}, lender evidence "
         f"{W['lender_evidence']}, availability {W['availability']}, same community {W['same_community']}, freshness "
         f"{W['freshness']}. Relevance = {MIX['semantic']} x semantic + {MIX['keyword']} x keyword. Lender evidence = "
         f"posterior mean if n_eff >= {N_MIN:g}, else the population baseline ({POP_BASELINE}). Freshness = "
         f"2^(-age / {HALF_LIFE:g} days). Items with relevance below {MIN_REL} are dropped.", "",
         "| Rank | Item | Semantic | Keyword | Relevance | Lender evidence | Availability | Same community | Freshness | Score |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for rank, (it, rel, p, total) in enumerate(kept, 1):
        L.append(f"| {rank} | {it[0]} {it[1]} | {it[2]:.2f} | {it[3]:.2f} | {rel:.3f} | {p['lender_evidence']:.2f} | "
                 f"{p['availability']:.1f} | {p['same_community']:.0f} | {p['freshness']:.3f} | **{total:.3f}** |")
    dropped = [r for r in rows if r[1] < MIN_REL]
    L += ["", "Dropped below the relevance floor: " + (", ".join(f"{r[0][0]} {r[0][1]} (relevance {r[1]:.3f})"
                                                       for r in dropped) or "none") + ".", ""]
    by = {r[0][0]: r for r in rows}
    i2 = by["I2"]
    same_but_known = sum(W[k] * v for k, v in {**i2[2], "lender_evidence": POP_BASELINE}.items())
    L += ["**What the example shows**", "",
          f"- I2's lender has no history, so it gets the baseline {POP_BASELINE}, not 0.5 or a low bound; its score "
          f"{i2[3]:.3f} equals what an established lender with mean {POP_BASELINE} would get ({same_but_known:.3f}). "
          "A newcomer is never ranked down for lack of history (claim C5).",
          f"- I3 matches well ({by['I3'][1]:.3f}) but its dates are taken, so availability 0 costs it "
          f"{W['availability']:.2f} and it falls below items that can actually be borrowed.",
          f"- I5 is as relevant as I1 but sits in the borrower's second community, so it loses the same-community "
          f"{W['same_community']:.2f}; it is still shown, because the borrower is a member there.",
          "- I4 has no keyword match but some meaning match; it ranks low and stays above the floor.",
          "- I6 is dropped: its meaning match is too weak, whatever its lender evidence. Trust never lifts an irrelevant item.",
          "", "**Reason line shown to the borrower** (never the score, FR-S-01 and NFR-U-01), for rank 1: "
          "\"Matches 'drill'; free on your dates; in your community; lender has a confirmed record of items as described.\""]
    out = os.path.join(HERE, "ranking_example_results.md")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")
    print(out, "written;", " > ".join(r[0][0] for r in kept))


if __name__ == "__main__":
    main()
